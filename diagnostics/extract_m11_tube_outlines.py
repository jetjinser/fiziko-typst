#!/usr/bin/env python3
"""Export instrument_m11_tube_outlines.py records as Typst polygons.

Usage: extract_m11_tube_outlines.py TRACE_LOG OUTPUT_TYP [PAGE_HEIGHT_MM]
"""

import re
import sys
from collections import defaultdict
from pathlib import Path


RECORD = re.compile(r"M11TO (-?\d+) (\d+) ([0-9.]+) ([0-9.]+) ([0-9.]+)")


def main() -> None:
    if len(sys.argv) not in (3, 4):
        raise SystemExit(__doc__)
    page_height = float(sys.argv[3]) if len(sys.argv) == 4 else 44.0
    grouped: dict[tuple[int, int], list[tuple[float, float, float]]] = defaultdict(list)
    for rank, segment, time, x, y in RECORD.findall(Path(sys.argv[1]).read_text()):
        grouped[(int(rank), int(segment))].append(
            (float(time), float(x), page_height - float(y))
        )
    if not grouped:
        raise ValueError("trace log contains no M11TO records")

    lines = [
        "// Generated by diagnostics/extract_m11_tube_outlines.py.",
        "// Coordinates are Typst page millimetres; source page height is 44 mm.",
        "#let upstream-m11-tube-outlines = (",
    ]
    for key in sorted(grouped):
        points = sorted(grouped[key])
        lines.append(f"  ((rank: {key[0]}, segment: {key[1]}), (")
        lines.extend(f"    ({x:.5f}, {y:.5f})," for _, x, y in points)
        lines.append("  )),")
    lines.append(")")
    Path(sys.argv[2]).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
