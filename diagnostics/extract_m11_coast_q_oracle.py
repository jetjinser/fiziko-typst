#!/usr/bin/env python3
"""Generate a Typst recursion probe with source M11 coast root q cubics.

Usage: extract_m11_coast_q_oracle.py MPOST_LOG TYPST_TRACE OUTPUT.typ [Q_ARC_TRACE]
"""

import json
import sys
from pathlib import Path


def fixed(value: str) -> int:
    whole, high, low = map(int, value.split(":"))
    return whole * 65536 + high * 256 + low


def source_roots(path: str) -> dict[int, list[tuple[int, int]]]:
    active = False
    mass = 0
    knots: list[tuple[int, int]] = []
    roots: dict[int, list[tuple[int, int]]] = {}
    for line in Path(path).read_text().splitlines():
        fields = line.split()
        if fields[:1] == ["M11-COAST-BEGIN"]:
            mass = int(fields[1])
            active = True
            knots = []
        elif fields[:1] == ["M11-COAST-END"]:
            active = False
        elif active and fields[:1] == ["M11-ROOTQ"]:
            if int(fields[1]) == mass:
                knots.append((fixed(fields[3]), fixed(fields[4])))
        elif active and fields[:1] == ["M11-COAST"]:
            roots[mass] = knots
            knots = []
    return roots


def source_root_curves(path: str) -> dict[int, list[tuple[tuple[int, int], ...]]]:
    active = False
    mass = 0
    segments: dict[int, dict[int, tuple[int, int]]] = {}
    roots: dict[int, list[tuple[tuple[int, int], ...]]] = {}
    for line in Path(path).read_text().splitlines():
        fields = line.split()
        if fields[:1] == ["M11-COAST-BEGIN"]:
            mass = int(fields[1])
            active = True
            segments = {}
        elif fields[:1] == ["M11-COAST-END"]:
            active = False
        elif active and fields[:1] == ["M11-ROOTQC"]:
            segment, control = map(int, fields[2:4])
            segments.setdefault(segment, {})[control] = (
                fixed(fields[4]), fixed(fields[5]))
        elif active and fields[:1] == ["M11-COAST"]:
            curves = []
            for segment in range(len(segments)):
                points = segments[segment]
                if sorted(points) != [0, 1, 2, 3]:
                    raise ValueError(f"mass {mass}: incomplete source q segment {segment}")
                curves.append(tuple(points[index] for index in range(4)))
            roots[mass] = curves
            segments = {}
    return roots


def typst(value) -> str:
    if isinstance(value, dict):
        return "(" + ", ".join(f"{key}: {typst(item)}" for key, item in value.items()) + ",)"
    if isinstance(value, (list, tuple)):
        return "(" + ", ".join(typst(item) for item in value) + ",)"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    raise TypeError(type(value))


def q_curves(knots: list[tuple[int, int]]) -> list[tuple]:
    return [
        (a, (a[0] + round((b[0] - a[0]) / 3),
             a[1] + round((b[1] - a[1]) / 3)),
         (a[0] + round(2 * (b[0] - a[0]) / 3),
          a[1] + round(2 * (b[1] - a[1]) / 3)), b)
        for a, b in zip(knots, knots[1:])
    ]


def main() -> None:
    if len(sys.argv) not in (4, 5):
        raise SystemExit(__doc__)
    log, trace_path, output = sys.argv[1:4]
    roots = source_roots(log)
    root_curves = source_root_curves(log)
    trace = json.loads(Path(trace_path).read_text())
    qarc = None if len(sys.argv) == 4 else {
        entry["landmass"]: entry["source-q-arc-positions"]
        for entry in json.loads(Path(sys.argv[4]).read_text())
    }
    cases = []
    for entry in trace:
        mass = entry["landmass"]
        if mass not in roots:
            continue
        knots = roots[mass]
        if qarc is not None:
            if mass not in qarc or len(qarc[mass]) != len(knots):
                raise ValueError(f"q arc count does not match source knots for mass {mass}")
            knots = [
                (round(arc / (25.4 / 72) * 65536), width)
                for arc, (_, width) in zip(qarc[mass], knots)
            ]
        if qarc is None:
            q = root_curves.get(mass)
            if q is None:
                raise ValueError(f"mass {mass}: source trace has no M11-ROOTQC controls")
        else:
            q = q_curves(knots)
        if q is None:
            raise ValueError(f"mass {mass}: source trace has no M11-ROOTQC controls")
        cases.append({
            "landmass": mass,
            "points": entry["outline-points"],
            "times": entry["source-times"],
            "end": entry["source-time-end"],
            "q": q,
        })
    if not cases:
        raise SystemExit("no source/Typst coast roots could be paired")
    source = '''// Generated by extract_m11_coast_q_oracle.py; diagnostic only.
#import "../fiziko.typ": stroke-ink, _source-min-stroke, _source-dash-length
#let cases = CASES
#let result = cases.map(case => {
  let width(t) = _source-min-stroke
  let ink = stroke-ink(case.points, width, closed: true, per: 0,
    min-w: _source-min-stroke, period: _source-dash-length,
    _source-rounding: true, _with-stats: true, _trace-nodes: true,
    _param-times: case.times, _param-end: case.end,
    _source-q-curves-fixed: case.q)
  (landmass: case.landmass, calls: ink.at(1), outer: ink.at(2).outer,
    thin: ink.at(2).thin, dashes: ink.at(2).dashes, nodes: ink.at(2).nodes)
})
#metadata(result) <m11-coast-source-q-oracle>
'''.replace("CASES", typst(cases))
    Path(output).write_text(source)
    print(f"wrote {len(cases)} source q root cases to {output}")


if __name__ == "__main__":
    main()
